/** First-visit language: Chinese for any `zh*` browser locale, otherwise English. */
export function detectLanguage(browserLanguages: readonly string[]): Language {
  return browserLanguages[0]?.toLowerCase().startsWith("zh") ? "zh" : "en";
}
